# Online install: detect platform
detect_platform() {
	OS=$(uname -s)
	ARCH=$(uname -m)

	case "$ARCH" in
		amd64|x86_64)  ARCH="x86_64" ;;
		arm64|aarch64) ARCH="aarch64" ;;
		loongarch64|loong64) ARCH="loongarch64" ;;
	esac

	case "${OS}-${ARCH}" in
		Linux-x86_64)
			PKG_GNU="safe-rm-v${VERSION}-linux-x86_64-gnu.tar.gz"
			PKG_MUSL="safe-rm-v${VERSION}-linux-x86_64-musl.tar.gz"
			;;
		Linux-aarch64)
			PKG_GNU="safe-rm-v${VERSION}-linux-aarch64-gnu.tar.gz"
			PKG_MUSL="safe-rm-v${VERSION}-linux-aarch64-musl.tar.gz"
			;;
		Linux-loongarch64)
			PKG_GNU="safe-rm-v${VERSION}-linux-loongarch64-gnu.tar.gz"
			PKG_MUSL=""
			;;
		FreeBSD-x86_64)
			PKG_GNU="safe-rm-v${VERSION}-freebsd-x86_64.tar.gz"
			PKG_MUSL=""
			;;
		Darwin-x86_64)
			PKG_GNU="safe-rm-v${VERSION}-macos-x86_64.tar.gz"
			PKG_MUSL=""
			;;
		Darwin-aarch64)
			PKG_GNU="safe-rm-v${VERSION}-macos-aarch64.tar.gz"
			PKG_MUSL=""
			;;
		*)
			error "$MSG_UNSUPPORTED ${OS} ${ARCH}"
			;;
	esac

	if [ -n "$PKG_GNU" ]; then
		URL_GNU="${BASE_URL}/${PKG_GNU}"
		DIR_GNU=$(basename "$PKG_GNU" .tar.gz)
	fi
	if [ -n "$PKG_MUSL" ]; then
		URL_MUSL="${BASE_URL}/${PKG_MUSL}"
		DIR_MUSL=$(basename "$PKG_MUSL" .tar.gz)
	fi

	info "OS:   ${OS}"
	info "ARCH: ${ARCH}"
}

# Online install: download
download() {
	URL="$1"
	PKG="$2"

	TMPDIR=$(mktemp -d)
	cd "$TMPDIR"

	info "$MSG_DOWNLOADING"
	info "$URL"

	curl -fL --progress-bar -o "$PKG" "$URL" || {
		cd /
		rm -rf "$TMPDIR"
		return 1
	}
	return 0
}

# Online install: extract
extract() {
	PKG="$1"
	DIR="$2"

	info "$MSG_EXTRACTING"
	tar xzf "$PKG" || {
		cd /
		rm -rf "$TMPDIR"
		return 1
	}
	cd "$DIR"
	return 0
}

# Cleanup installed files (used for fallback)
cleanup_installed() {
	rm -f "$BINDIR/safe-rm"
	rm -f "$BINDIR/update-safe-rm"
	rm -f "$SYSCONFDIR/safe-rm.conf"
	rm -f "$PROFILEDIR/safe-rm.sh"
	rm -rf "$SYMLINKDIR"
	rmdir "$PREFIX/share/safe-rm" 2>/dev/null || true
	rm -f "$MANDIR/safe-rm.1"
	rm -rf "$DOCDIR"
}

# Local install from current directory
install_from_cwd() {
	SELECTED_MSG="$1"

	check_files
	check_installed

	info "$MSG_INSTALL $PREFIX ..."

	# 1. Binary
	install -d "$BINDIR"
	install -m 755 safe-rm "$BINDIR/safe-rm"

	# 2. Config
	install -d "$SYSCONFDIR"
	if [ ! -f "$SYSCONFDIR/safe-rm.conf" ]; then
		install -m 644 safe-rm.conf "$SYSCONFDIR/safe-rm.conf"
	fi

	# 3. PATH script
	install -d "$PROFILEDIR"
	install -m 644 safe-rm.sh "$PROFILEDIR/safe-rm.sh"

	# 4. Symlink
	install -d "$SYMLINKDIR"
	ln -sf "$BINDIR/safe-rm" "$SYMLINKDIR/rm"

	# 5. Update script
	install -m 755 update-safe-rm "$BINDIR/update-safe-rm"

	# 6. Man page
	install -d "$MANDIR"
	install -m 644 safe-rm.1 "$MANDIR/safe-rm.1"

	# 7. Documentation
	install -d "$DOCDIR"
	for f in README.md INSTALL COPYING Changes install.sh; do
		if [ -f "$f" ]; then
			install -m 644 "$f" "$DOCDIR/"
		fi
	done

	# 8. Verify binary can run
	SAFE_RM_OUT=$("$BINDIR/safe-rm" --version 2>&1)
	SAFE_RM_RC=$?
	if [ "$SAFE_RM_RC" -ne 0 ]; then
		return 1
	fi
	case "$SAFE_RM_OUT" in
		*GLIBC_*|*"not found"*|*"version "*" not found"*)
			return 1
			;;
	esac

	if [ -n "$SELECTED_MSG" ]; then
		info "$SELECTED_MSG"
	fi

	info "$MSG_DONE"
	echo ""

	# 1. Installed files
	echo "$MSG_INSTALLED_FILES"
	echo "  $BINDIR/safe-rm"
	echo "  $SYMLINKDIR/rm"
	echo "  $SYSCONFDIR/safe-rm.conf"
	echo "  $PROFILEDIR/safe-rm.sh"
	echo "  $BINDIR/update-safe-rm"
	echo "  $MANDIR/safe-rm.1"
	echo "  $DOCDIR/"
	if [ -d "$DOCDIR" ]; then
		for f in "$DOCDIR"/*; do
			[ -e "$f" ] && echo "    $(basename "$f")"
		done
	fi
	echo ""

	# 2. Update protection list
	echo "$MSG_UPDATE_TITLE"
	echo ""
	echo "  update-safe-rm              # $MSG_UPDATE_CONF"
	echo ""
	printf "%b\n" "$MSG_UPDATE_DESC"
	echo ""

	# 3. Re-login hint
	echo "$MSG_RELOGIN"
	echo "  . $PROFILEDIR/safe-rm.sh"
	echo ""

	# 4. Test
	echo "$MSG_TEST"
	echo "  rm -rf /tmp"
	echo "  # safe-rm: Skipping /tmp."
	echo ""

	# 5. PATH setup
	echo "$MSG_PATH_SETUP"
	echo "  $MSG_PATH_STANDARD $PROFILEDIR/safe-rm.sh"
	echo "  $MSG_PATH_OVERRIDE"
	echo ""
	echo "    bash: echo 'export PATH=\"$SYMLINKDIR:\$PATH\"' >> ~/.bashrc"
	echo "    zsh:  echo 'export PATH=\"$SYMLINKDIR:\$PATH\"' >> ~/.zshrc"
	echo "    sh:   echo 'PATH=\"$SYMLINKDIR:\$PATH\"' >> ~/.profile"
	echo "    csh:  echo 'set path = ($SYMLINKDIR \$path)' >> ~/.cshrc"
	echo ""

	# 6. Project homepage
	echo "$MSG_HOMEPAGE $HOMEPAGE"
	echo ""

	# 7. safe-rm help
	if [ -x "$BINDIR/safe-rm" ]; then
		"$BINDIR/safe-rm" --help
	fi
}

# Try online install for one package
try_online_install() {
	URL="$1"
	PKG="$2"
	DIR="$3"
	SELECTED_MSG="$4"

	download "$URL" "$PKG" || return 1
	extract "$PKG" "$DIR" || return 1

	if [ -f "safe-rm" ] && [ -f "safe-rm.conf" ] && [ -f "safe-rm.sh" ] \
		&& [ -f "update-safe-rm" ] && [ -f "safe-rm.1" ]; then
		install_from_cwd "$SELECTED_MSG" || return 1
		return 0
	fi

	return 1
}

# Install
do_install() {
	check_root

	# Case 1: complete local files in current directory -> local install
	if [ -f "safe-rm" ] && [ -f "safe-rm.conf" ] && [ -f "safe-rm.sh" ] \
		&& [ -f "update-safe-rm" ] && [ -f "safe-rm.1" ]; then
		install_from_cwd ""
		return
	fi

	# Case 2: online install
	check_installed
	check_tools
	detect_platform

	# Try gnu first
	if [ -n "$PKG_GNU" ]; then
		info "$MSG_TRY_GNU"
		if try_online_install "$URL_GNU" "$PKG_GNU" "$DIR_GNU" "$MSG_GNU_SELECTED"; then
			cd /
			rm -rf "$TMPDIR"
			return 0
		fi
		# gnu failed: cleanup and try musl
		cleanup_installed
		cd /
		rm -rf "$TMPDIR"
		warn "$MSG_FALLBACK_MUSL"
	fi

	# Try musl
	if [ -n "$PKG_MUSL" ]; then
		info "$MSG_TRY_MUSL"
		if try_online_install "$URL_MUSL" "$PKG_MUSL" "$DIR_MUSL" "$MSG_MUSL_SELECTED"; then
			cd /
			rm -rf "$TMPDIR"
			return 0
		fi
		cleanup_installed
		cd /
		rm -rf "$TMPDIR"
	fi

	print_system_info
	error "$MSG_BOTH_FAILED"
}

# Uninstall
do_uninstall() {
	check_root

	info "$MSG_UNINSTALL"

	# 1. Binaries
	rm -f "$BINDIR/safe-rm"
	rm -f "$BINDIR/update-safe-rm"

	# 2. Config
	rm -f "$SYSCONFDIR/safe-rm.conf"

	# 3. PATH script
	rm -f "$PROFILEDIR/safe-rm.sh"

	# 4. Symlink directory
	rm -rf "$SYMLINKDIR"
	rmdir "$PREFIX/share/safe-rm" 2>/dev/null || true

	# 5. Man page
	rm -f "$MANDIR/safe-rm.1"

	# 6. Documentation
	rm -rf "$DOCDIR"

	# 7. Legacy paths (for compatibility across versions)
	rm -f /etc/profile.d/safe-rm.sh
	rm -f /usr/local/etc/profile.d/safe-rm.sh
	rm -f /etc/safe-rm.conf
	rm -f /usr/local/etc/safe-rm.conf

	info "$MSG_UNINSTALLED"
}

# Usage
usage() {
	cat << EOF
safe-rm installer (integrated)

Usage: $0 [OPTIONS]

Options:
  -h, --help        Show this help
  -u, --uninstall   Uninstall safe-rm

Environment:
  VERSION      Version to install for online mode (default: ${VERSION})
  PREFIX       Install prefix (default: /usr/local)
  SYSCONFDIR   Config dir (default: /etc on Linux, /usr/local/etc on FreeBSD/macOS)
  MANDIR       Man dir (default: \$PREFIX/share/man/man1)
  DOCDIR       Doc dir (default: \$PREFIX/share/doc/safe-rm)

Local install:
  sh install.sh
  PREFIX=/opt/safe-rm sudo ./install.sh
  sh install.sh --uninstall

Online install:
  curl -fsSL https://raw.githubusercontent.com/${REPO}/master/install.sh | sudo sh
  VERSION=1.1.0 sudo sh install.sh
  sudo sh install.sh --uninstall

Homepage: $HOMEPAGE
EOF
}

# Main
case "${1:-}" in
	-h|--help)
		usage
		exit 0
		;;
	-u|--uninstall)
		do_uninstall
		;;
	"")
		do_install
		;;
	*)
		usage
		exit 1
		;;
esac